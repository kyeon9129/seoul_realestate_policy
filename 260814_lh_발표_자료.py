"""#국토부 실거래 API 함수"""

# ============================================================
# 국토교통부 아파트 매매 실거래가 API 함수
# ============================================================

import requests
import pandas as pd
import xml.etree.ElementTree as ET
import time


API_URL = (
    "https://apis.data.go.kr/1613000/"
    "RTMSDataSvcAptTradeDev/"
    "getRTMSDataSvcAptTradeDev"
)


def fetch_apt_trade(lawd_cd, deal_ymd, num_rows=1000):

    """
    국토교통부 아파트 매매 실거래가 API

    Parameters
    ----------
    lawd_cd : str
        법정동 시군구 코드 앞 5자리
        예) 종로구 11110

    deal_ymd : str
        계약년월 YYYYMM
        예) 202509

    num_rows : int
        페이지당 요청 데이터 수

    Returns
    -------
    pandas.DataFrame
    """

    all_rows = []

    page_no = 1


    while True:

        params = {

            # Decoding 인증키 사용
            "serviceKey": APT_KEY,

            # 지역코드
            "LAWD_CD": str(lawd_cd),

            # 계약년월
            "DEAL_YMD": str(deal_ymd),

            # 페이지
            "pageNo": page_no,

            # 페이지당 데이터 수
            "numOfRows": num_rows
        }


        # ----------------------------------------------------
        # API 요청
        # ----------------------------------------------------

        try:

            response = requests.get(
                API_URL,
                params=params,
                timeout=30
            )


        except requests.exceptions.RequestException as error:

            print(
                f"API 연결 오류 | "
                f"{lawd_cd} / {deal_ymd}"
            )

            print(error)

            return pd.DataFrame()


        # ----------------------------------------------------
        # HTTP 상태 확인
        # ----------------------------------------------------

        if response.status_code != 200:

            print("=" * 60)

            print(
                f"API HTTP 오류 | "
                f"{lawd_cd} / {deal_ymd}"
            )

            print(
                "HTTP 상태코드 :",
                response.status_code
            )

            print("\n서버 응답 내용")

            print(
                response.text[:1000]
            )

            print("=" * 60)

            return pd.DataFrame()


        # ----------------------------------------------------
        # XML 파싱
        # ----------------------------------------------------

        try:

            root = ET.fromstring(
                response.content
            )


        except ET.ParseError:

            print(
                f"XML 변환 실패 | "
                f"{lawd_cd} / {deal_ymd}"
            )

            print(
                response.text[:1000]
            )

            return pd.DataFrame()


        # ----------------------------------------------------
        # 공공데이터 API 결과코드 확인
        # ----------------------------------------------------

        result_code = root.findtext(
            ".//resultCode"
        )

        result_msg = root.findtext(
            ".//resultMsg"
        )


        if result_code not in [
            "000",
            "00",
            None
        ]:

            print("=" * 60)

            print("공공데이터 API 응답 오류")

            print(
                "resultCode :",
                result_code
            )

            print(
                "resultMsg :",
                result_msg
            )

            print("=" * 60)

            return pd.DataFrame()


        # ----------------------------------------------------
        # 거래자료 추출
        # ----------------------------------------------------

        items = root.findall(
            ".//item"
        )


        page_rows = []


        for item in items:

            row = {}


            for child in item:

                if child.text is None:

                    row[child.tag] = ""

                else:

                    row[child.tag] = (
                        child.text.strip()
                    )


            page_rows.append(row)


        all_rows.extend(
            page_rows
        )


        # ----------------------------------------------------
        # 전체 데이터 수
        # ----------------------------------------------------

        total_count_text = (
            root.findtext(
                ".//totalCount"
            )
        )


        if total_count_text:

            total_count = int(
                total_count_text
            )

        else:

            total_count = len(
                all_rows
            )


        # ----------------------------------------------------
        # 진행상황 확인
        # ----------------------------------------------------

        print(
            f"{lawd_cd} / {deal_ymd} "
            f"| {len(all_rows):,}"
            f"/{total_count:,}건"
        )


        # ----------------------------------------------------
        # 모든 데이터 수집 완료
        # ----------------------------------------------------

        if len(all_rows) >= total_count:

            break


        if len(page_rows) == 0:

            break


        page_no += 1

        # 서버 과부하 방지
        time.sleep(0.05)


    return pd.DataFrame(
        all_rows
    )

