def refine_transactions(df):

    df = df.copy()


    # --------------------------------------------------------
    # 필요한 컬럼 확인
    # --------------------------------------------------------

    required_cols = [

        "dealYear",
        "dealMonth",
        "dealDay",
        "dealAmount",
        "excluUseAr",
        "aptNm",
        "region"
    ]


    missing_cols = [

        col

        for col in required_cols

        if col not in df.columns
    ]


    if len(missing_cols) > 0:

        raise ValueError(
            f"필수 컬럼 누락 : {missing_cols}"
        )


    # --------------------------------------------------------
    # 컬럼 이름 정리
    # --------------------------------------------------------

    rename_dict = {

        "aptNm":
        "apartment_name",

        "umdNm":
        "dong_name",

        "dealAmount":
        "deal_amount_manwon",

        "excluUseAr":
        "area_m2",

        "floor":
        "floor",

        "buildYear":
        "build_year",

        "cdealDay":
        "cancel_date_raw"
    }


    df.rename(

        columns=rename_dict,

        inplace=True
    )


    # --------------------------------------------------------
    # 날짜 숫자형 변환
    # --------------------------------------------------------

    df["dealYear"] = pd.to_numeric(
        df["dealYear"],
        errors="coerce"
    )

    df["dealMonth"] = pd.to_numeric(
        df["dealMonth"],
        errors="coerce"
    )

    df["dealDay"] = pd.to_numeric(
        df["dealDay"],
        errors="coerce"
    )


    # --------------------------------------------------------
    # 실제 계약일 생성
    # --------------------------------------------------------

    df["deal_date"] = pd.to_datetime(

        {

            "year": df["dealYear"],

            "month": df["dealMonth"],

            "day": df["dealDay"]
        },

        errors="coerce"
    )


    # --------------------------------------------------------
    # 거래금액
    # API 단위 = 만원
    # --------------------------------------------------------

    df["deal_amount_manwon"] = (

        df["deal_amount_manwon"]

        .astype(str)

        .str.replace(
            ",",
            "",
            regex=False
        )

        .str.strip()
    )


    df["deal_amount_manwon"] = (
        pd.to_numeric(

            df["deal_amount_manwon"],

            errors="coerce"
        )
    )


    # 억원 단위 컬럼
    df["price_eok"] = (

        df["deal_amount_manwon"]

        / 10000
    )


    # --------------------------------------------------------
    # 전용면적
    # --------------------------------------------------------

    df["area_m2"] = pd.to_numeric(

        df["area_m2"],

        errors="coerce"
    )


    # --------------------------------------------------------
    # 계약해제 거래 제거
    # --------------------------------------------------------

    if "cancel_date_raw" not in df.columns:

        df["cancel_date_raw"] = ""


    df["cancel_date_raw"] = (

        df["cancel_date_raw"]

        .fillna("")

        .astype(str)

        .str.strip()
    )


    cancelled = (

        df["cancel_date_raw"] != ""
    )


    print(
        "계약해제 거래 제외 :",
        cancelled.sum(),
        "건"
    )


    df = df[
        ~cancelled
    ].copy()


    # --------------------------------------------------------
    # 필수값 결측치 제거
    # --------------------------------------------------------

    df = df.dropna(

        subset=[

            "deal_date",
            "region",
            "deal_amount_manwon"
        ]
    )


    # --------------------------------------------------------
    # 완전 중복행 제거
    # --------------------------------------------------------

    df = df.drop_duplicates()


    df.reset_index(
        drop=True,
        inplace=True
    )


    return df


